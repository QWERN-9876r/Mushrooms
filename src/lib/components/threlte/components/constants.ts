export const getRandomMushroom = (
    luckMultiplier = luckPercentToMultiplier(BASE_LUCK_PERCENT),
) => {
    const legendaryChance = Math.min(0.05, 0.01 * luckMultiplier)
    const rareChance = Math.min(0.3, 0.09 * luckMultiplier)
    const rarityRoll = Math.random()

    if (rarityRoll < legendaryChance) {
        return LEGENDARY_MUSHROOMS[
            Math.floor(Math.random() * LEGENDARY_MUSHROOMS.length)
        ]
    }
    if (rarityRoll < legendaryChance + rareChance) {
        return RARE_MUSHROOMS[Math.floor(Math.random() * RARE_MUSHROOMS.length)]
    }
    return SIMPLE_MUSHROOMS[Math.floor(Math.random() * SIMPLE_MUSHROOMS.length)]
}
